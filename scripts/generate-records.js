#!/usr/bin/env node
/**
 * Generates generated/records/ for the `@hypercerts-org/lexicon/records`
 * subpath: lex-compatible record schemas for @atproto/lex, one module per
 * lexicon, plus an index with one named export per record type.
 *
 * - Runs the modern @atproto/lex generator (`lex build`) over every lexicon
 *   except permission sets, so referenced definitions are included.
 * - Sorts the namespace re-exports lex writes, so the output does not depend
 *   on the order the generator reads files in.
 * - Writes generated/records/index.ts. Record names follow the package's
 *   existing NSID constants: ACTIVITY_NSID -> `activity` (schema) and
 *   `Activity` (type), VOCAB_TAG_NSID -> `vocabTag` and `VocabTag`.
 *
 * The legacy `lex` CLI (@atproto/lex-cli) also installs a `lex` binary, so
 * this script runs @atproto/lex's own entry point directly.
 */

import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { pathToImportName, pathToNamespace } from "./lexicon-names.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const projectRoot = join(__dirname, "..");
const lexiconsDir = join(projectRoot, "lexicons");
const outDir = join(projectRoot, "generated", "records");
const lexEntry = join(
  projectRoot,
  "node_modules",
  "@atproto",
  "lex",
  "bin",
  "lex",
);

const header = `/*
 * THIS FILE WAS GENERATED BY scripts/generate-records.js. DO NOT EDIT.
 */
`;

/** Plain code-unit comparison, independent of locale. */
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0);

/**
 * All lexicon JSON files, as POSIX paths relative to lexicons/, with their
 * parsed documents.
 */
function readLexicons() {
  return readdirSync(lexiconsDir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".json"))
    .map((entry) => {
      const file = join(entry.parentPath, entry.name);
      const path = relative(lexiconsDir, file).split(sep).join("/");
      try {
        return { path, doc: JSON.parse(readFileSync(file, "utf-8")) };
      } catch (error) {
        const message = error instanceof Error ? error.message : String(error);
        throw new Error(`Failed to parse lexicon ${path}: ${message}`);
      }
    })
    .sort((a, b) => byCodeUnit(a.path, b.path));
}

/** Converts SCREAMING_SNAKE to camelCase: BADGE_AWARD -> badgeAward. */
function camelCase(name) {
  return name
    .toLowerCase()
    .replace(/_([a-z0-9])/g, (_match, letter) => letter.toUpperCase());
}

/** Sorts the `export * as x from` lines in lex's namespace files. */
function sortNamespaceExports(dir) {
  const files = readdirSync(dir, { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile() && entry.name.endsWith(".ts"))
    .filter((entry) => !entry.name.endsWith(".defs.ts"))
    .map((entry) => join(entry.parentPath, entry.name));
  for (const file of files) {
    const lines = readFileSync(file, "utf-8").split("\n");
    const exports = lines.filter((line) => line.startsWith("export * as "));
    if (exports.length < 2) continue;
    const sorted = [...exports].sort(byCodeUnit);
    let next = 0;
    const result = lines.map((line) =>
      line.startsWith("export * as ") ? sorted[next++] : line,
    );
    writeFileSync(file, result.join("\n"));
  }
}

function indexSource(lexicons) {
  const lines = [
    header,
    "// Lex-compatible schemas for @atproto/lex: one named export per record",
    "// type (`activity`) with its TypeScript type (`Activity`), and every",
    "// lexicon as a namespace (`OrgHypercertsClaimActivity`) for the types of",
    "// its other definitions.",
    "",
  ];
  /** @type {Set<string>} */
  const names = new Set();
  const claim = (name, path) => {
    if (names.has(name)) {
      throw new Error(`Two lexicons map to the export name ${name} (${path})`);
    }
    names.add(name);
  };

  for (const { path, doc } of lexicons) {
    if (doc.defs?.main?.type !== "record") continue;
    const schema = camelCase(
      pathToImportName(path).replace(/_LEXICON_JSON$/, ""),
    );
    const type = schema[0].toUpperCase() + schema.slice(1);
    claim(schema, path);
    claim(type, path);
    const from = JSON.stringify(`./${path.replace(/\.json$/, "")}.defs.js`);
    lines.push(
      `export { main as ${schema}, type Main as ${type} } from ${from};`,
    );
  }
  lines.push("");
  for (const { path } of lexicons) {
    const namespace = pathToNamespace(path);
    claim(namespace, path);
    const from = JSON.stringify(`./${path.replace(/\.json$/, "")}.js`);
    lines.push(`export * as ${namespace} from ${from};`);
  }
  return `${lines.join("\n")}\n`;
}

function main() {
  const lexicons = readLexicons().filter(
    ({ doc }) => doc?.defs?.main?.type !== "permission-set",
  );
  const permissionSets = readLexicons()
    .filter(({ doc }) => doc?.defs?.main?.type === "permission-set")
    .map(({ doc }) => doc.id);

  execFileSync(
    process.execPath,
    [
      lexEntry,
      "build",
      "--lexicons",
      lexiconsDir,
      "--out",
      outDir,
      "--clear",
      ...(permissionSets.length > 0 ? ["--exclude", ...permissionSets] : []),
    ],
    { stdio: ["ignore", "ignore", "inherit"] },
  );
  sortNamespaceExports(outDir);
  writeFileSync(join(outDir, "index.ts"), indexSource(lexicons));

  const records = lexicons.filter(
    ({ doc }) => doc.defs?.main?.type === "record",
  );
  console.log(
    `✅ Generated generated/records/ (${records.length} records, ${lexicons.length} lexicons)`,
  );
}

main();
